import { StrictMode } from 'react'
import { createRoot } from 'react-dom/client'
import { RouterProvider, createRouter } from '@tanstack/react-router'
import { QueryClient, QueryClientProvider } from '@tanstack/react-query'

// Tailwind entry + the shadcn-style HSL token definitions (:root + .dark).
// UI-REVIEW fix (Phase 28): this import was missing, so Tailwind was never
// loaded and every className-based style in the app (including all the
// `bg-primary` / `text-muted-foreground` / `bg-background` utilities used by
// the shadcn ui/ components and the TestRunner) generated zero CSS. Importing
// it here makes the token system live and fixes dark mode app-wide.
import './global.css'

// Generated by @tanstack/router-plugin (vite) from src/routes/*.tsx — the
// file-based routing codegen replaces the stale hand-maintained tree (D-22-06).
import { routeTree } from './routeTree.gen'

import { AuthProvider } from '@/lib/auth-context'

// Create router instance
const router = createRouter({ routeTree })

// Register router for type safety
declare module '@tanstack/react-router' {
  interface Register {
    router: typeof router
  }
}

// Phase 28 (Plan 28-02, Critical Finding 2): TanStack Query was installed but
// unused — no QueryClientProvider existed. Wrapping the app here enables
// useQuery/useMutation across the tree, including D-08 (useQuery over
// GET /v1/engines for the TestRunner engine-selector dropdown) and D-10
// (useMutation for executeRule). Defaults are safe for the app shell; the
// TestRunner component tests create a fresh QueryClient per test.
const queryClient = new QueryClient()

const rootElement = document.getElementById('root')!
if (!rootElement.innerHTML) {
  const root = createRoot(rootElement)
  root.render(
    <StrictMode>
      <QueryClientProvider client={queryClient}>
        <AuthProvider>
          <RouterProvider router={router} />
        </AuthProvider>
      </QueryClientProvider>
    </StrictMode>
  )
}